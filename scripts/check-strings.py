#!/usr/bin/env python3
"""Checks that every L("...") string in the Swift sources is translated, and keeps the languages consistent.

Usage:
  scripts/check-strings.py             # exit 1 on a missing key, a format-specifier mismatch or an empty translation
  scripts/check-strings.py --sync-en   # rewrite en.lproj/Localizable.strings from the code (English text is the key)

Keys are the English text. A missing translation would silently fall back to English at runtime, which is
exactly what this check exists to catch.
"""
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCALES = ROOT / "packaging/locales"
LANGS = ["en", "es", "de"]
CALL = re.compile(r'\bL\(\s*"((?:[^"\\]|\\.)*)"')
ENTRY = re.compile(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";\s*$')
SPEC = re.compile(r"%(?:\d+\$)?(?:ll|l|h)?[@dDuUxXoOfeEgGcCsSp]")
INFO_KEYS = ["NSAppleEventsUsageDescription"]


def code_keys():
    seen = {}
    for path in sorted((ROOT / "Sources").rglob("*.swift")):
        for key in CALL.findall(path.read_text(encoding="utf-8")):
            seen.setdefault(key, path.relative_to(ROOT))
    return seen


def read_strings(path):
    entries = {}
    if not path.exists():
        return entries
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith(("/*", "//", "*")):
            continue
        match = ENTRY.match(line)
        if not match:
            raise SystemExit(f"{path.relative_to(ROOT)}:{number}: cannot parse line: {line[:70]}")
        entries[match.group(1)] = match.group(2)
    return entries


def specifiers(text):
    return Counter(spec[-1].replace("D", "d").replace("U", "u") for spec in SPEC.findall(text))


def sync_en(keys):
    out = LOCALES / "en.lproj/Localizable.strings"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ["/* English: the key is the text. Generated by scripts/check-strings.py --sync-en; do not edit. */"]
    lines += [f'"{key}" = "{key}";' for key in keys]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(keys)} strings)")


def main():
    keys = code_keys()
    if "--sync-en" in sys.argv:
        sync_en(list(keys))
        return
    problems = []
    for lang in LANGS:
        table = read_strings(LOCALES / f"{lang}.lproj/Localizable.strings")
        for key, source in keys.items():
            if key not in table:
                problems.append(f"[{lang}] missing: {key[:70]!r} (used in {source})")
            elif not table[key].strip():
                problems.append(f"[{lang}] empty translation: {key[:70]!r}")
            elif specifiers(key) != specifiers(table[key]):
                problems.append(f"[{lang}] format specifiers differ: {key[:60]!r} -> {table[key][:60]!r}")
        for stale in sorted(set(table) - set(keys)):
            problems.append(f"[{lang}] stale (no longer in the code): {stale[:70]!r}")
        info = read_strings(LOCALES / f"{lang}.lproj/InfoPlist.strings")
        problems += [f"[{lang}] InfoPlist.strings missing {k}" for k in INFO_KEYS if not info.get(k, "").strip()]
    if problems:
        print("\n".join(problems))
        print(f"\n{len(problems)} problem(s)")
        sys.exit(1)
    print(f"ok: {len(keys)} strings in {len(LANGS)} languages")


if __name__ == "__main__":
    main()
